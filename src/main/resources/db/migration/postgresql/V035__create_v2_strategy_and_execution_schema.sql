-- Indexes for performance & quick crash recovery lookups
CREATE INDEX IF NOT EXISTS idx_positions_status_date ON positions (position_status, entry_time);
CREATE INDEX IF NOT EXISTS idx_sim_positions_status_date ON simulated_positions (position_status, entry_time);
CREATE INDEX IF NOT EXISTS idx_signals_symbol_date ON signals (symbol, signal_time);
CREATE INDEX IF NOT EXISTS idx_sim_signals_symbol_date ON simulated_signals (symbol, signal_time);
CREATE INDEX IF NOT EXISTS idx_orders_symbol_date ON orders (symbol, placed_at);
CREATE INDEX IF NOT EXISTS idx_sim_orders_symbol_date ON simulated_orders (symbol, placed_at);

