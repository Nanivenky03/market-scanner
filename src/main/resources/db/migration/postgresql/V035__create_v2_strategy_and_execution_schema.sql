-- V035: Create V2 Strategy, Signals, Orders, and Positions Schema

CREATE TABLE IF NOT EXISTS strategy_config (
    id INTEGER PRIMARY KEY,
    strategy_key TEXT NOT NULL,
    strategy_name TEXT NOT NULL,
    description TEXT,
    priority INTEGER NOT NULL,
    execution_mode TEXT NOT NULL DEFAULT 'PAPER',
    allocated_capital DOUBLE PRECISION NOT NULL DEFAULT 50000.0,
    risk_per_trade_inr DOUBLE PRECISION NOT NULL DEFAULT 1000.0,
    max_daily_trades INTEGER NOT NULL DEFAULT 5,
    max_daily_losses INTEGER NOT NULL DEFAULT 3,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TEXT NOT NULL,
    updated_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS strategy_rule_value (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    strategy_id INTEGER NOT NULL REFERENCES strategy_config(id),
    rule_key TEXT NOT NULL,
    rule_value TEXT NOT NULL,
    value_type TEXT NOT NULL,
    description TEXT,
    created_at TEXT NOT NULL,
    updated_at TEXT NOT NULL,
    CONSTRAINT uq_strategy_rule UNIQUE (strategy_id, rule_key)
);

